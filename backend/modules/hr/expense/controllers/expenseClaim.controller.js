/**
 * GET /api/expense/claims
 * Employees (or scope=my): own claims + submitted claims they are tagged on.
 * Staff: company-wide register (drafts stay private to their creator).
 */
exports.listClaims = async (req, res) => {
  try {
    const companyId = access.resolveCompanyId(req, { allowAll: true });
    const page = Math.max(1, parseInt(req.query.page, 10) || 1);
    const limit = Math.min(5000, Math.max(1, parseInt(req.query.limit, 10) || 20));
    const uid = req.user._id;
    const and = buildFilters(req.query);
    if (companyId && companyId !== 'ALL') and.push({ companyId });

    const isMyScope = req.query.scope === 'my' || !access.isStaff(req.user);
    if (isMyScope) {
      if (req.query.excludeTagged === 'true') {
        and.push({ submittedBy: uid });
      } else {
        and.push({ $or: [{ submittedBy: uid }, { 'employeeClaims.employee.employeeId': uid, status: { $ne: 'DRAFT' } }] });
      }
    } else if (access.isAccounts(req.user) && !access.isCompanyAdmin(req.user) && !access.isHR(req.user)) {
      and.push({
        $or: [
          {
            status: { $nin: [...access.DRAFT_STATUSES, ...access.APPROVAL_PENDING_STATUSES] },
            'managerApproval.status': { $nin: ['PENDING', 'REJECTED'] },
            'financeApproval.status': { $nin: ['PENDING', 'REJECTED'] },
          },
          { submittedBy: uid },
        ],
      });
    } else {
      and.push({
        $or: [
          {
            status: { $nin: [...access.DRAFT_STATUSES, ...access.APPROVAL_PENDING_STATUSES] },
            'managerApproval.status': { $ne: 'PENDING' },
            'financeApproval.status': { $ne: 'PENDING' },
          },
          { submittedBy: uid },
        ],
      });
    }
    const filter = and.length ? { $and: and } : {};

    const [claims, total] = await Promise.all([
      ExpenseClaim.find(filter)
        .populate(LIST_POPULATE)
        .sort({ createdAt: -1 })
        .skip((page - 1) * limit)
        .limit(limit)
        .lean(),
      ExpenseClaim.countDocuments(filter),
    ]);

    res.json({
      success: true,
      data: claims.map((c) => userShare(c, uid, req)),
      total,
      page,
      pages: Math.ceil(total / limit),
    });
  } catch (err) {
    res.status(err.status || 500).json({ success: false, message: err.message });
  }
};

